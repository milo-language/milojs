#!/usr/bin/env node
// lib/module.js's `builtinModules` is what `module.isBuiltin` and every package
// that probes for core modules reads (is-core-module requires all of them). It
// was hand-kept and had already drifted: dns, vm, worker_threads and nine others
// were requirable but absent from the list, so is-core-module answered false for
// modules this runtime has.
//
// So derive it. The specifiers this runtime can actually require are the string
// literals in builtinSource() in src/runtime/modules.milo; node's own
// module.builtinModules decides which of those are NODE modules rather than this
// runtime's internal shims (prelude, temporal, _errors, qjs:*). Nothing is
// listed by hand on either side.
//
//   node tools/gen-builtins.mjs           rewrite the list
//   node tools/gen-builtins.mjs --check   fail if it is stale (CI/precommit)
import { readFileSync, writeFileSync } from 'node:fs';
import { builtinModules } from 'node:module';

const check = process.argv.includes('--check');
const MODULES_MILO = 'src/runtime/modules.milo';
const MODULE_JS = 'lib/module.js';

const milo = readFileSync(MODULES_MILO, 'utf8');
const start = milo.indexOf('fn builtinSource');
if (start < 0) {
  console.error(`gen-builtins: no builtinSource() in ${MODULES_MILO}`);
  process.exit(1);
}
const end = milo.indexOf('\nfn ', start + 10);
const body = milo.slice(start, end < 0 ? milo.length : end);

const known = new Set(builtinModules.flatMap((m) => [m, m.replace(/^node:/, '')]));
const names = [...new Set([...body.matchAll(/name == "([^"]+)"/g)].map((m) => m[1]))]
  .filter((n) => known.has(n))
  .sort();

if (names.length === 0) {
  console.error('gen-builtins: matched 0 specifiers — the parse stopped matching');
  process.exit(1);
}

const BEGIN = '// GENERATED by tools/gen-builtins.mjs — do not edit by hand';
const END = '];';
const js = readFileSync(MODULE_JS, 'utf8');
const bi = js.indexOf('var builtinModules = [');
if (bi < 0) {
  console.error(`gen-builtins: no builtinModules array in ${MODULE_JS}`);
  process.exit(1);
}
const ei = js.indexOf(END, bi);
// Wrap at a width that keeps the array readable in a diff.
const lines = [];
let line = ' ';
for (const n of names) {
  const item = ` "${n}",`;
  if (line.length + item.length > 78) { lines.push(line); line = ' '; }
  line += item;
}
if (line.trim()) lines.push(line);
const block = `${BEGIN}\nvar builtinModules = [\n${lines.join('\n')}\n];`;
const out = js.slice(0, bi).replace(new RegExp(`${BEGIN}\\n$`), '') + block + js.slice(ei + END.length);

if (check) {
  if (out !== js) {
    console.error(`gen-builtins: ${MODULE_JS} builtinModules is stale — run: node tools/gen-builtins.mjs`);
    process.exit(1);
  }
  console.log(`gen-builtins: ${names.length} builtin specifiers, list is current`);
} else {
  writeFileSync(MODULE_JS, out);
  console.log(`gen-builtins: wrote ${names.length} builtin specifiers to ${MODULE_JS}`);
}
